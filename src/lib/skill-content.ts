/** 用输入参数填充 {{param}} 占位符 */
export function fillTemplate(template: string, input: SkillInput): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_match, key: string) => {
    const value = input[key];
    return value === undefined || value === null || value === '' ? '—' : String(value);
  });
}

